def patch_hub():
    """The hub's header is hand-written and not in modules(), so it is done
    separately. Marker-delimited like everything else, so re-running replaces
    rather than appends."""
    path = os.path.join(ROOT, "index.html")
    src = open(path, encoding="utf-8").read()
    src = TRACKS_BLOCK.sub("", src)

    anchor = src.find('<button id="themeToggle"')
    if anchor == -1:
        return False
    line = src.rfind("\n", 0, anchor) + 1
    src = src[:line] + "                " + tracks_menu("") + "\n" + src[line:]
    open(path, "w", encoding="utf-8").write(src)
    return True


def main():
    mods = modules()
    groups = by_topic()
    by_path = {m["path"]: m for m in mods}

    files = sorted(glob.glob(os.path.join(ROOT, "*", "*.html")))
    files = [f for f in files
             if os.path.basename(os.path.dirname(f)) not in ("tools", "assets", "node_modules")]

    prose_tagged = 0

    injected = shared = bylines = tracked = 0
    fallback_used = 0
    missing_anchor = []

    for f in files:
        rel = os.path.relpath(f, ROOT)
        mod = by_path.get(rel)
        if not mod:
            continue
        root_prefix = "../" * rel.count("/")
        src = open(f, encoding="utf-8").read()

        # Drop previous output first, so the summary is never re-extracted
        # from a cheat sheet we generated on an earlier run.
        src = BLOCK.sub("", src)
        src = SHARE_BLOCK.sub("", src)
        src = SAVE_BLOCK.sub("", src)
        src = BYLINE_BLOCK.sub("", src)
        src = TRACKS_BLOCK.sub("", src)

        summary = lead_paragraph(src, mod["desc"])
        if summary == mod["desc"]:
            fallback_used += 1

        # Related: the next few modules in the same track, wrapping around.
        peers = groups[mod["topic"]]
        i = next(k for k, p in enumerate(peers) if p["path"] == rel)
        related = [peers[(i + n) % len(peers)] for n in range(1, RELATED_COUNT + 1)]
        related = [r for r in related if r["path"] != rel][:RELATED_COUNT]

        prev = peers[i - 1] if i > 0 else None
        nxt = peers[i + 1] if i < len(peers) - 1 else None

        block = build_block(mod, summary, related, prev, nxt, root_prefix, rel)

        # Anchor on the footer's *marker*, not on "<footer" itself: the footer
        # is generated between VIZLEARN:FOOTER markers, so anchoring on the
        # element would place this block inside that region - and the next
        # `build_footer` run would then delete this block along with the
        # footer it replaces.
        anchor = src.rfind("<!-- VIZLEARN:FOOTER:BEGIN")
        if anchor == -1:
            anchor = src.rfind("<footer")
        if anchor == -1:
            anchor = src.rindex("</body>")
        anchor = src.rfind("\n", 0, anchor) + 1
        src = src[:anchor] + block + src[anchor:]
        injected += 1

        # Byline, immediately after the page title.
        hm = re.search(r"</h1>", src)
        if hm:
            src = src[:hm.end()] + "\n            " + byline(mod, rel, root_prefix) + \
                src[hm.end():]
            bylines += 1

        # Tag the long-form prose so the glossary layer can find it.
        #
        # 55 modules use .vz-article, which is both a hook and a set of
        # typography rules. The other 170 predate it and wrap their prose in
        # ad-hoc Tailwind classes, so the glossary silently did nothing on
        # them. Adding .vz-article to those pages would restyle 170 published
        # articles; this adds a styling-free attribute instead, on the section
        # build_articles.py already marks.
        am = src.find(ARTICLE_MARKER)
        if am != -1:
            sm = src.find("<section", am)
            if sm != -1:
                close = src.find(">", sm)
                tag = src[sm:close]
                if "data-vz-prose" not in tag:
                    src = src[:close] + " data-vz-prose" + src[close:]
                    prose_tagged += 1
        elif "data-vz-prose" not in src and 'class="vz-article' not in src:
            # Two pages carry no marker but put their article in a
            # <main class="... prose">, which is Tailwind Typography's own
            # name for exactly this. Only those two match site-wide, and the
            # element holds the article alone - the visualisation is above it.
            pm = PROSE_MAIN.search(src)
            if pm:
                close = pm.end() - 1
                src = src[:close] + " data-vz-prose" + src[close:]
                prose_tagged += 1

        # Share and save controls, immediately before the theme toggle in
        # the header. Save goes in first so that, inserted at the same
        # anchor, the rendered order reads share-then-save.
        tm = src.find('<button id="themeToggle"')
        if tm == -1:
            missing_anchor.append(rel)
        else:
            line = src.rfind("\n", 0, tm) + 1
            src = src[:line] + "                    " + SAVE_MARKUP + "\n" + src[line:]
            line = src.rfind("\n", 0, src.find(SAVE_BEGIN)) + 1
            src = src[:line] + "                    " + SHARE_MARKUP + "\n" + src[line:]
            line = src.rfind("\n", 0, src.find(SHARE_BEGIN)) + 1
            src = src[:line] + "                    " + tracks_menu(root_prefix) + "\n" + src[line:]
            shared += 1
            tracked += 1

        open(f, "w", encoding="utf-8").write(src)

    print("modules updated        : %d" % injected)
    print("prose sections tagged  : %d" % prose_tagged)
    print("bylines added          : %d" % bylines)
    print("share controls added   : %d" % shared)
    print("tracks menus added     : %d%s" % (tracked, " (+ the hub)" if patch_hub() else ""))
    print("cheat sheets using the meta description as fallback : %d" % fallback_used)
    if missing_anchor:
        print("\nNO THEME TOGGLE (share control skipped) on %d page(s):" % len(missing_anchor))
        for r in missing_anchor:
            print("  -", r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
