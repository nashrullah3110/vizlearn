def card(mod, root_prefix):
    art = mod["svg"].strip()
    if art.startswith("<svg") and "xmlns=" not in art:
        art = art.replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"', 1)
    return (
        '<a class="vz-card" href="%s%s" data-vz-path="%s">'
        '<span class="vz-card-art">%s</span>'
        '<span class="vz-card-body">'
        '<span class="vz-card-cat">%s</span>'
        '<span class="vz-card-title">%s</span>'
        "</span></a>"
        % (root_prefix, mod["path"], html.escape(mod["path"]), art,
           html.escape(mod["category"]), html.escape(mod["title"]))
    )


def prevnext(prev, nxt, root_prefix):
    if not prev and not nxt:
        return ""
    out = ['<nav class="vz-prevnext" aria-label="Module navigation">']
    if prev:
        out.append(
            '<a class="vz-pn vz-pn-prev" href="%s%s" rel="prev">%s'
            '<span class="vz-pn-text"><span class="vz-pn-label">Previous</span>'
            '<span class="vz-pn-title">%s</span></span></a>'
            % (root_prefix, prev["path"], svg("left"), html.escape(prev["title"]))
        )
    if nxt:
        out.append(
            '<a class="vz-pn vz-pn-next" href="%s%s" rel="next">'
            '<span class="vz-pn-text"><span class="vz-pn-label">Next</span>'
            '<span class="vz-pn-title">%s</span></span>%s</a>'
            % (root_prefix, nxt["path"], html.escape(nxt["title"]), svg("right"))
        )
    out.append("</nav>")
    return "".join(out)


def build_block(mod, summary, related, prev, nxt, root_prefix, rel):
    cheat = (
        '<section class="vz-cheatsheet" aria-labelledby="vz-cheat-h">'
        '<div class="vz-cheat-top">'
        '<span class="vz-cheat-label">%s Cheat sheet</span>'
        '<button type="button" class="vz-btn" data-vz-copy>%s Copy</button>'
        "</div>"
        '<h2 class="vz-cheat-title" id="vz-cheat-h">%s</h2>'
        '<p class="vz-cheat-text">%s</p>'
        '<div class="vz-cheat-foot">%s &middot; vizlearn.in/%s</div>'
        "</section>"
        % (svg("note"), svg("copy"), html.escape(mod["title"]), html.escape(summary),
           html.escape(mod["category"].upper()), html.escape(mod["path"]))
    )

    rail = (
        '<section class="vz-related" aria-labelledby="vz-rel-h">'
        '<div class="vz-section-head">%s<h2 id="vz-rel-h">More in %s</h2>'
        '<span class="vz-rule"></span></div>'
        '<div class="vz-rail">%s</div>'
        "</section>"
        % (svg("grid"), html.escape(mod["category"]),
           "".join(card(r, root_prefix) for r in related))
    )

    return "%s\n<div class=\"vz-extras\">%s%s%s%s%s</div>\n%s\n" % (
        BEGIN, cheat, rail, further_reading(rel), author_card(root_prefix),
        prevnext(prev, nxt, root_prefix), END
    )


def byline(mod, rel, root_prefix):
    """Track, author and last-updated date, directly under the page title.

    No page carried a date before. Readers of a technical explainer reasonably
    want to know whether they are looking at something maintained, and a
    crawler has nothing to read freshness from without it - the same date goes
    into `dateModified` in the JSON-LD and into the sitemap.
    """
    iso = last_modified(rel)
    key = DIR_TO_TOPIC.get(mod["dir"])
    track = TOPICS[key]["title"] if key else mod["category"]
    href = "%s%s/" % (root_prefix, mod["dir"])

    # The author was named in the docstring, in <meta name="author"> and in the
    # JSON-LD, and nowhere a reader could see it. Who wrote a technical
    # explainer is the first thing anyone assessing it looks for.
    return (
        BYLINE_BEGIN
        + '<p class="vz-byline">'
          '<a class="vz-byline-track" href="%s">%s</a>'
          '<span class="vz-byline-sep" aria-hidden="true">&middot;</span>'
          '<span>By <a class="vz-byline-author" rel="author" href="%sabout.html">%s</a></span>'
          '<span class="vz-byline-sep" aria-hidden="true">&middot;</span>'
          '<span>Updated <time datetime="%s">%s</time></span>'
          "</p>"
        % (href, html.escape(track), root_prefix, html.escape(AUTHOR), iso, pretty_date(iso))
        + BYLINE_END
    )


def further_reading(rel):
    """Primary sources for this module, where there are genuine ones to cite.

    Pages with nothing real to point at get no section - a filler link is
    worse than an absent one.
    """
    refs = REFERENCES.get(rel)
    if not refs:
        return ""
    items = []
    for title, source, url in refs:
        name = html.escape(title)
        if url:
            name = '<a href="%s" rel="noopener nofollow">%s</a>' % (html.escape(url), name)
        items.append('<li><span class="vz-ref-title">%s</span>'
                     '<span class="vz-ref-src">%s</span></li>'
                     % (name, html.escape(source)))
    return (
        '<section class="vz-refs" aria-labelledby="vz-refs-h">'
        '<h2 id="vz-refs-h" class="vz-refs-h">Further reading</h2>'
        '<ul class="vz-ref-list">%s</ul>'
        "</section>" % "".join(items)
    )


def author_card(root_prefix):
    """Short bio under the article.

    A named byline says who; this says on what basis. Both are the visible
    half of what the JSON-LD already claims about authorship.
    """
    return (
        '<section class="vz-author" aria-labelledby="vz-author-h">'
        '<h2 id="vz-author-h" class="vz-author-h">About the author</h2>'
        '<p class="vz-author-body"><strong>%s</strong> builds and maintains VizLearn. '
        'Every module here is written and the visualisation behind it hand-built, '
        'so the numbers in a readout come from the same code that draws the picture. '
        'Corrections are genuinely welcome and get priority over everything else &mdash; '
        'if a page states something wrong, or an animation misrepresents what the '
        'algorithm does, <a href="%scontact.html">get in touch</a>.</p>'
        '<p class="vz-author-links">'
        '<a href="%sabout.html">About VizLearn</a>'
        '<span class="vz-byline-sep" aria-hidden="true">&middot;</span>'
        '<a href="https://github.com/AshishJangra27" rel="noopener me">GitHub</a>'
        '<span class="vz-byline-sep" aria-hidden="true">&middot;</span>'
        '<a href="https://www.linkedin.com/in/ashish-jangra/" rel="noopener me">LinkedIn</a>'
        '<span class="vz-byline-sep" aria-hidden="true">&middot;</span>'
        '<a href="%scontact.html">Contact</a>'
        "</p>"
        "</section>"
        % (html.escape(AUTHOR), root_prefix, root_prefix, root_prefix)
    )


SAVE_MARKUP = (
    SAVE_BEGIN
    + '<div class="vz-save-wrap">'
      '<button type="button" class="vz-save-btn" aria-label="Bookmark this module or add a note" '
      'aria-haspopup="true" aria-expanded="false">' + svg("bookmark") + "</button>"
      '<div class="vz-save-menu" role="dialog" aria-label="Bookmark and note"></div>'
      "</div>"
    + SAVE_END
)


SHARE_MARKUP = (
    SHARE_BEGIN
    + '<div class="vz-share-wrap">'
      '<button type="button" class="vz-share-btn" aria-label="Share this module" '
      'aria-haspopup="true" aria-expanded="false">' + svg("share") + "</button>"
      '<div class="vz-share-menu" role="menu"></div>'
      "</div>"
    + SHARE_END
)


