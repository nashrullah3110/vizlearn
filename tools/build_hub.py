#!/usr/bin/env python3
"""Build the homepage's featured lessons and supporting sections.

The opening presents six concrete lessons, then a short route for new visitors.
The full track catalogue follows. Secondary study tools sit after the catalogue
so they do not compete with the first choice.

Everything this writes lives between VIZLEARN:HUB markers and is replaced on
re-run, so it is safe in the build chain. The intro band it removes is
recorded here rather than deleted from history: three cards and a "New here?"
note, one <section class="vz-intro-band">, whose heading existed only to
introduce those cards.

The numbers in the sections come from the catalog, so they cannot drift from
the real module counts.

    python3 tools/build_hub.py
"""

import html
import os
import re
import sys

from home_copy import FEATURED
from lib_catalog import counts, modules

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "index.html")

BEGIN_TOP = "<!-- VIZLEARN:HUB-TOP:BEGIN (generated by tools/build_hub.py) -->"
END_TOP = "<!-- VIZLEARN:HUB-TOP:END -->"
BEGIN_BOT = "<!-- VIZLEARN:HUB-BOTTOM:BEGIN (generated by tools/build_hub.py) -->"
END_BOT = "<!-- VIZLEARN:HUB-BOTTOM:END -->"

# The leading whitespace is part of the match: the block is written with
# its own indentation, and stripping only the markers leaves that behind to
# accumulate a blank line on every rebuild.
TOP_BLOCK = re.compile(r"[ \t]*" + re.escape(BEGIN_TOP) + r".*?" + re.escape(END_TOP) + r"\n?", re.S)
BOT_BLOCK = re.compile(r"[ \t]*" + re.escape(BEGIN_BOT) + r".*?" + re.escape(END_BOT) + r"\n?", re.S)
INTRO_BAND = re.compile(r'\s*<section class="vz-intro-band".*?</section>', re.S)
STUDY_TOOLS_NAV = re.compile(r'\s*<nav aria-label="Study tools".*?</nav>\s*', re.S)
MODULE_STAT = re.compile(r'(<(?:span|strong) id="stat-modules">)\d+(</(?:span|strong)>)')
TRACK_STAT = re.compile(r'(<(?:span|strong) id="stat-tracks">)\d+(</(?:span|strong)>)')

ANCHOR_TOP = '<main id="course-container"'
ANCHOR_BOT = "<!-- VIZLEARN:FOOTER:BEGIN"


def esc(s):
    return html.escape(str(s))


# --------------------------------------------------------------------------
# Sections
# --------------------------------------------------------------------------

def featured():
    """Six illustrated examples plus a small live experiment.

    The compact KNN experiment gives visitors one immediate interaction. The
    six lesson cards below it use the catalog's own artwork and concise hooks;
    copy lives in tools/home_copy.py.
    """
    by = {m["path"]: m for m in modules(with_desc=False)}
    cards = []
    for path, blurb in FEATURED:
        m = by.get(path)
        if not m:
            raise SystemExit("featured module not in the catalog: %s" % path)
        art = m["svg"].strip()
        if art.startswith("<svg") and "xmlns=" not in art:
            art = art.replace("<svg", '<svg xmlns="http://www.w3.org/2000/svg"', 1)
        cards.append(
            '<article class="vzx-panel vzx-start-card vzx-featured-card">'
            '<div class="vzx-featured-art" aria-hidden="true">%s</div>'
            '<div class="vzx-featured-copy"><span class="vzx-start-track">%s</span>'
            '<h3 class="vzx-start-title"><a href="%s" data-vz-path="%s">%s</a></h3>'
            '<p class="vzx-start-p">%s</p>'
            '<span class="vzx-start-go" aria-hidden="true">Open lesson &rarr;</span></div>'
            '</article>'
            % (art, esc(m["category"]), esc(path), esc(path), esc(m["title"]), esc(blurb)))
    return ('<section class="vzx-sec" id="featured-lessons" aria-labelledby="vzx-start-h"><div class="vzx-wrap">'
            '<p class="vzx-kicker">Featured</p>'
            '<h2 class="vzx-h" id="vzx-start-h">Try an idea, then choose what to learn next</h2>'
            '<p class="vzx-sub">Move the query point and change k. The neighbours vote again each time.</p>'
            '%s<div class="vzx-start vzx-featured-grid">%s</div>%s</div></section>'
            % (knn_demo(), "".join(cards), learning_path_prompt()))


