#!/usr/bin/env python3
"""Restructure index.html: remove the intro band, add the hub sections.

The hub opened with four blocks of prose before it reached a single module,
which is backwards for a site whose argument is that you should go and push a
slider. It now opens on sixteen featured modules, each with a two-sentence
reason to open it (tools/home_copy.py), then the track cards, and keeps the
explanatory material below them. A chart of modules per track used to sit
below as well; the track cards carry the same numbers, and it repeated all
eighteen track links twice.

Everything this writes lives between VIZLEARN:HUB markers and is replaced on
re-run, so it is safe in the build chain. The intro band it removes is
recorded here rather than deleted from history: three cards and a "New here?"
note, one <section class="vz-intro-band">, whose heading existed only to
introduce those cards.

The numbers in the sections come from the catalog, so they cannot drift from
the real module counts.

    python3 tools/build_hub.py
"""

import html
import os
import re
import sys

from home_copy import FEATURED
from lib_catalog import counts, modules

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "index.html")

BEGIN_TOP = "<!-- VIZLEARN:HUB-TOP:BEGIN (generated by tools/build_hub.py) -->"
END_TOP = "<!-- VIZLEARN:HUB-TOP:END -->"
BEGIN_BOT = "<!-- VIZLEARN:HUB-BOTTOM:BEGIN (generated by tools/build_hub.py) -->"
END_BOT = "<!-- VIZLEARN:HUB-BOTTOM:END -->"

# The leading whitespace is part of the match: the block is written with
# its own indentation, and stripping only the markers leaves that behind to
# accumulate a blank line on every rebuild.
TOP_BLOCK = re.compile(r"[ \t]*" + re.escape(BEGIN_TOP) + r".*?" + re.escape(END_TOP) + r"\n?", re.S)
BOT_BLOCK = re.compile(r"[ \t]*" + re.escape(BEGIN_BOT) + r".*?" + re.escape(END_BOT) + r"\n?", re.S)
INTRO_BAND = re.compile(r'\s*<section class="vz-intro-band".*?</section>', re.S)

ANCHOR_TOP = '<main id="course-container"'
ANCHOR_BOT = '<footer class="vz-footer"'


def esc(s):
    return html.escape(str(s))


# --------------------------------------------------------------------------
# Sections
# --------------------------------------------------------------------------

def featured():
    """Sixteen modules across the tracks, two sentences each.

    This was "Start here": the first module of six tracks, title only. The
    homepage now opens on the track cards below it, so this is the place for
    a short, written reason to open a particular page. Copy lives in
    tools/home_copy.py; the paragraph sits outside the link, as on the track
    cards.
    """
    by = {m["path"]: m for m in modules(with_desc=False)}
    cards = []
    for path, blurb in FEATURED:
        m = by.get(path)
        if not m:
            raise SystemExit("featured module not in the catalog: %s" % path)
        cards.append(
            '<div class="vzx-panel vzx-start-card"><span class="vzx-start-track">%s</span>'
            '<h3 class="vzx-start-title"><a href="%s">%s</a></h3>'
            '<p class="vzx-start-p">%s</p></div>'
            % (esc(m["category"]), esc(path), esc(m["title"]), esc(blurb)))
    return ('<section class="vzx-sec" aria-labelledby="vzx-start-h"><div class="vzx-wrap">'
            '<p class="vzx-kicker">Featured</p>'
            '<h2 class="vzx-h" id="vzx-start-h">Sixteen places to start</h2>'
            '<p class="vzx-sub">One or two from each of the main tracks, chosen because '
            'the visualisation does the explaining. Every one runs in the browser, with '
            'the written guide underneath.</p><div class="vzx-start">%s</div></div></section>'
            % "".join(cards))


def how_it_works():
    steps = [
        ("Pick the idea, not the chapter",
         "Every module is one concept with one visualisation. There is no chapter to "
         "finish before it makes sense, and no order you have to arrive in."),
        ("Drive it until it breaks",
         "The controls are the point. Set k to 1 and watch KNN overfit, push the "
         "learning rate until descent diverges. Understanding usually arrives at the "
         "failure, not the happy path."),
        ("Read the code that did it",
         "Where it helps, the same page carries a Python editor running the real thing "
         "in your browser. Change a line, run it, see the output move."),
    ]
    body = "".join(
        '<div class="vzx-step"><span class="vzx-step-n">%d</span><div class="vzx-step-body">'
        '<h3 class="vzx-step-h">%s</h3><p class="vzx-step-p">%s</p></div></div>'
        % (i, esc(t), esc(b)) for i, (t, b) in enumerate(steps, 1))
    return ('<section class="vzx-sec" aria-labelledby="vzx-how-h"><div class="vzx-wrap">'
            '<p class="vzx-kicker">How it works</p>'
            '<h2 class="vzx-h" id="vzx-how-h">Three steps, then you are just using it</h2>'
            '<p class="vzx-sub">No account, no install, nothing gated. Open a page and it '
            'runs.</p><div class="vzx-steps">%s</div></div></section>' % body)


def faq():
    qs = [
        ("Is it actually free?",
         "Yes, and there is nothing to sign up for. No account, no trial, no email wall."),
        ("Does the Python really run?",
         "It runs CPython compiled to WebAssembly, in a worker thread in your browser. "
         "Nothing is uploaded and nothing is executed on a server."),
        ("Does it work offline?",
         "The site installs as an app and caches what you have opened, so pages you have "
         "already visited keep working without a connection."),
        ("Who is it for?",
         "Anyone who has read the definition and still cannot picture the thing. It "
         "assumes no maths degree and leaves nothing as an exercise for the reader."),
    ]
    items = "".join('<div class="vzx-panel vzx-faq-item"><h3 class="vzx-faq-q">%s</h3>'
                    '<p class="vzx-faq-a">%s</p></div>' % (esc(q), esc(a)) for q, a in qs)
    return ('<section class="vzx-sec" aria-labelledby="vzx-faq-h"><div class="vzx-wrap">'
            '<p class="vzx-kicker">Questions</p>'
            '<h2 class="vzx-h" id="vzx-faq-h">The ones worth answering up front</h2>'
            '<div class="vzx-faq">%s</div></div></section>' % items)


def cta(n_mods):
    return ('<section class="vzx-sec vzx-sec-cta"><div class="vzx-wrap"><div class="vzx-cta">'
            '<h2 class="vzx-h" style="margin-top:0">Open one and push a slider</h2>'
            '<p class="vzx-sub" style="margin:0 auto">That is the whole pitch. %d modules, '
            'all of them running the real computation, none of them asking you for '
            'anything first.</p><div class="vzx-cta-row">'
            '<a class="vzx-btn vzx-btn-solid" href="dsa/big_o_notation.html">Start with Big-O</a>'
            '<a class="vzx-btn vzx-btn-ghost" href="map/">Browse the concept map</a>'
            '</div></div></div></section>' % n_mods)


HUB_JS = """<script>
(function () {
  // Suppress transitions for the frame the theme class flips in, so nothing
  // on the page tries to interpolate its colours.
  var root = document.documentElement;
  function guard() {
    root.classList.add('vz-swapping');
    requestAnimationFrame(function () {
      requestAnimationFrame(function () { root.classList.remove('vz-swapping'); });
    });
  }
  document.addEventListener('click', function (e) {
    if (e.target.closest && e.target.closest('#themeToggle, .theme-toggle')) guard();
  }, true);
})();
</script>"""


def main():
    src = open(INDEX, encoding="utf-8").read()
    n = counts()

    removed = bool(INTRO_BAND.search(src))
    src = INTRO_BAND.sub("", src)
    src = TOP_BLOCK.sub("", src)
    src = BOT_BLOCK.sub("", src)

    top = "%s\n%s\n%s\n    " % (BEGIN_TOP, featured(), END_TOP)
    bottom = "%s\n%s%s%s\n%s\n%s\n    " % (
        BEGIN_BOT,
        how_it_works(), faq(), cta(n["modules"]), HUB_JS, END_BOT)

    at = src.find(ANCHOR_TOP)
    if at == -1:
        raise SystemExit("anchor %r not found" % ANCHOR_TOP)
    src = src[:at] + top + src[at:]

    at = src.find(ANCHOR_BOT)
    if at == -1:
        raise SystemExit("anchor %r not found" % ANCHOR_BOT)
    src = src[:at] + bottom + src[at:]

    open(INDEX, "w", encoding="utf-8").write(src)
    print("hub sections    : featured modules above the tracks, steps/questions below")
    print("intro band      : %s" % ("removed" if removed else "already gone"))
    print("numbers         : %d modules, %d tracks (from the catalog)"
          % (n["modules"], n["tracks"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
