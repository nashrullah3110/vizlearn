# A readout is a leaf element - one whose content is text, not more markup.
# Matching only leaves is what keeps this from picking up whole panels.
READ_TAG = re.compile(
    r'<(span|div|p|strong|b|td|h[2-6])\b[^>]*\bid="([^"]+)"[^>]*>([^<]*)</\1>', re.I)

# Site furniture rather than anything the visualisation computes.
NOT_READOUT = re.compile(r"^(vz-|search|theme|nav|header|footer|menu|tooltip)", re.I)

# Ranking only - an id matching none of these is still a candidate, because
# plenty of pages name their outputs things like "stHit".
#
# The split matters. A derived metric makes a question worth asking ("what
# happens to accuracy when you double the true positives?"); a raw tally
# usually answers itself ("what happens to the total?"). Both are real
# readouts, so both are offered - the interesting one just goes first.
READOUT_DERIVED = re.compile(
    r"(accur|precis|recall|f1|score|loss|error|entrop|gini|margin|cost|"
    r"rate|prob|mean|avg|ratio|percent|pct|confid|spec|sensit|auc|r2|"
    r"pred|result|output|distance|similar|angle|weight|bias|grad)", re.I)
READOUT_TALLY = re.compile(
    r"(count|total|sum|size|len|num|steps?|swaps?|compar|ops|time|"
    r"hit|miss|node|depth|state|status|badge|display|value|val)", re.I)


def readouts(src, ctrls):
    """Elements on the page that display a computed value.

    Deliberately generous: 166 pages name their outputs 166 different ways
    ("stHit", "valMax", "step-badge", "live-calculation"), so anything that
    looks like a small text leaf with an id is offered as a candidate and the
    runtime picks the first one that is actually showing something.

    Two things are excluded, both for the same reason - they would make the
    prediction trivial rather than interesting:

      * the controls themselves;
      * any element whose starting text is simply a control's current value,
        which is how the pages mirror a slider's position next to its label.
    """
    from lib_controls import _label_before

    control_ids = set(c["id"] for c in ctrls)

    # Most pages mirror a slider's position in a <span> beside its label, named
    # after the same thing: "k-slider" is echoed by "k-value", "lr-slider" by
    # "lr-value". Those are not readouts - asking what happens to Weight w1
    # when you set Weight w1 is not a prediction - so match them by stem.
    #
    # Comparing the displayed text against the control's value is not enough:
    # a slider set to "1" is commonly displayed as "1.0".
    SUFFIX = re.compile(
        r"[-_]?(slider|input|select|range|box|field|btn|button|check|checkbox|"
        r"value|val|display|out|readout|num|txt|text|label)$", re.I)

    def stem(cid):
        prev = None
        while prev != cid:
            prev = cid
            cid = SUFFIX.sub("", cid)
        return cid.lower()

    control_stems = set(stem(c["id"]) for c in ctrls if stem(c["id"]))

    control_values = set()
    for c in ctrls:
        v = c.get("value")
        if v in (None, "", True, False):
            continue
        control_values.add(str(v).strip())
        try:
            # "1" and "1.0" are the same number even though they are not the
            # same string, and the mirror usually formats to a fixed width.
            control_values.add(("%g" % float(v)))
        except (TypeError, ValueError):
            pass

    def from_id(cid):
        """"stepBadge" -> "step badge"."""
        s = re.sub(r"([a-z])([A-Z])", r"\1 \2", cid)
        return s.replace("-", " ").replace("_", " ").strip().lower()

    found = []
    seen = set()
    used_labels = set()

    for m in READ_TAG.finditer(src):
        cid, inner = m.group(2), m.group(3)
        if cid in control_ids or cid in seen or NOT_READOUT.match(cid):
            continue
        if stem(cid) in control_stems:
            continue
        txt = text_of(inner)
        if len(txt) > 24 or txt in control_values:
            continue
        try:
            if ("%g" % float(txt)) in control_values:
                continue
        except (TypeError, ValueError):
            pass
        seen.add(cid)

        label = _label_before(src, m.start())
        # A row of metrics sits close enough together that the scan can pick up
        # the previous one's caption. If a name is already taken, it is the
        # wrong name for this element, so use its id instead.
        if not label or len(label) > 48 or label.lower() in used_labels:
            label = from_id(cid)
        used_labels.add(label.lower())

        # Whether a readout holds a number at *build* time says little: most
        # pages fill theirs in from JavaScript. It is a weak tie-break, not a
        # ranking - assets/vizlearn-lab.js re-checks against the live DOM.
        bucket = 2 if not txt else (0 if re.search(r"\d", txt) else 1)
        found.append({"id": cid, "label": label[:48], "_b": bucket})

    CHROME = re.compile(r"(badge|status|caption|heading|title|legend)", re.I)

    def key(e):
        blob = e["id"] + " " + e["label"]
        # A "badge" is decoration that usually just restates a control.
        if CHROME.search(e["id"]):
            name_rank = 3
        elif READOUT_DERIVED.search(blob):
            name_rank = 0
        elif READOUT_TALLY.search(blob):
            name_rank = 2
        else:
            name_rank = 1
        return (name_rank, e["_b"])

    out = sorted(found, key=key)[:10]
    for e in out:
        del e["_b"]
    return out


