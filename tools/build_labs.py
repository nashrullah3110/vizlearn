#!/usr/bin/env python3
"""Turn each module's written experiments into things you can actually run,
and add a prediction and an end-of-module check.

Every page already told you to "set the Neighbors (K) slider to 1" and then
left you to scroll up and do it by hand. This reads those instructions,
resolves them against the page's real controls, and attaches a button that
performs them - so the experiment the article describes is one click away from
the visualisation it describes.

Three blocks come out of it:

  * a `Run this` button on every experiment step that resolved to real control
    values (nothing is added to steps that did not resolve - a button that
    silently does nothing is worse than no button);
  * a predict-then-reveal panel, wired to one of those presets and to a real
    readout on the page, so the reveal is measured rather than scripted;
  * a check: multiple choice where tools/labs.py has questions for the module,
    retrieval flashcards built from the page's own key takeaways otherwise.

Idempotent: output lives between VIZLEARN:LAB markers plus the per-step
buttons, all of which are stripped before a re-run.
"""

