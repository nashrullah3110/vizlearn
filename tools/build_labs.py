def top_level_items(src, start):
    """Depth-aware scan of the first <ol>/<ul> after `start`.

    Returns [(open_end, close_start)] for each direct <li> child: the slice
    between them is that item's inner HTML, and close_start is where a button
    has to be inserted to land inside the item.
    """
    m = re.compile(r"<(ol|ul)\b[^>]*>", re.I).search(src, start, start + 4000)
    if not m:
        return []
    list_tag = m.group(1).lower()

    i = m.end()
    depth_list = 1
    depth_li = 0
    items = []
    open_end = None

    token = re.compile(r"</?(ol|ul|li)\b[^>]*>", re.I)
    while i < len(src):
        t = token.search(src, i)
        if not t:
            break
        tag = t.group(1).lower()
        closing = t.group(0).startswith("</")
        i = t.end()

        if tag in ("ol", "ul"):
            if closing:
                depth_list -= 1
                if depth_list == 0:
                    break
            else:
                depth_list += 1
        elif tag == "li":
            if closing:
                depth_li -= 1
                if depth_li == 0 and open_end is not None:
                    items.append((open_end, t.start()))
                    open_end = None
            else:
                if depth_li == 0 and depth_list == 1:
                    open_end = t.end()
                depth_li += 1

    return items


