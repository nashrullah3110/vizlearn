ARTICLE_START = re.compile(r"<!--\s*auto-article-vizlearn\s*-->", re.I)

# Headings that are navigation or instructions rather than an idea to recall.
SKIP_HEADING = re.compile(
    r"(exploration guide|guided experiment|try this|experiment with|more in |"
    r"check yourself|recall check|predict|cheat sheet|on this page|contents)", re.I)

PARA = re.compile(r"<p\b[^>]*>(.*?)</p>", re.S | re.I)


def _trim(body, limit=420):
    body = body.strip()
    if len(body) <= limit:
        return body
    cut = body.rfind(". ", 0, limit)
    return body[:cut + 1] if cut > limit // 2 else body[:limit].rstrip() + "..."


def flashcards(src):
    """Retrieval prompts built from the page's own writing.

    Three sources, in descending order of quality:

      1. a key-takeaway *list* of "<strong>Term:</strong> explanation" items,
         which is already a flashcard in everything but name;
      2. the single key-takeaway paragraph that most pages close on;
      3. the article's own section headings and their opening paragraph.

    Nothing is invented. Every answer shown is text the page already carries,
    which is the whole reason this is safe to generate for 166 pages - a
    machine-written distractor could easily be wrong, but a machine-selected
    quotation cannot.
    """
    cards = []

    # --- 1. a term/definition list --------------------------------------
    m = TAKEAWAY_HEAD.search(src)
    if m:
        for open_end, close_start in top_level_items(src, m.end()):
            tm = TERM_SPLIT.match(src[open_end:close_start].strip())
            if not tm:
                continue
            term = text_of(tm.group(1)).rstrip(":. ").strip()
            body = text_of(tm.group(2)).strip()
            if not term or len(term) > 70 or len(body) < 40:
                continue
            cards.append(("What is meant by “%s” here?" % term, _trim(body)))
        if len(cards) >= 2:
            return cards[:4]

    # --- 2. the one-paragraph takeaway ----------------------------------
    if m and not cards:
        pm = PARA.search(src, m.end(), m.end() + 2500)
        if pm:
            body = text_of(pm.group(1))
            if len(body) >= 60:
                cards.append(("Without scrolling back — what is the one-line "
                              "takeaway from this module?", _trim(body)))

    # --- 3. section headings --------------------------------------------
    am = ARTICLE_START.search(src)
    start = am.end() if am else 0
    stop = src.find("VIZLEARN:LAB:BEGIN")
    stop = len(src) if stop == -1 else stop

    for hm in re.finditer(r"<(h[3-4])\b[^>]*>(.*?)</\1>", src[start:stop], re.S | re.I):
        if len(cards) >= 3:
            break
        heading = text_of(hm.group(2)).strip()
        if not heading or len(heading) > 80 or SKIP_HEADING.search(heading):
            continue
        heading = re.sub(r"^\s*\d+[.)]\s*", "", heading)
        pm = PARA.search(src, start + hm.end(), start + hm.end() + 2000)
        if not pm:
            continue
        body = text_of(pm.group(1))
        if len(body) < 80:
            continue
        prompt = "What does this module say about “%s”?" % heading.rstrip("?:. ")
        if any(prompt == c[0] for c in cards):
            continue
        cards.append((prompt, _trim(body)))

    return cards[:4]


