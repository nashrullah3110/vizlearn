MIN_WORDS = {"minimum", "min", "lowest", "smallest"}
MAX_WORDS = {"maximum", "max", "highest", "largest", "its max"}

# Words too generic to safely identify a <select>/radio option by themselves.
STOPWORDS = {
    "all", "none", "the", "and", "or", "on", "off", "yes", "no", "one", "two",
    "set", "run", "data", "value", "type", "mode", "step", "next", "reset",
    "start", "stop", "true", "false", "default", "select", "column", "table",
}


def label_pattern(label):
    """Match a control label in prose, tolerating the quoting the pages use."""
    parts = [re.escape(w) for w in re.split(r"\s+", label.strip()) if w]
    if not parts:
        return None
    return re.compile(r"[\"'`“‘]?\s*" + r"[\s\-_]+".join(parts) +
                      r"\s*[\"'`”’]?", re.I)


def resolve_number(window, ctrl):
    """The value a numeric control should take, from the text after its label."""
    low = window.lower()
    head = low[:70]
    if any(w in head for w in MAX_WORDS) and ctrl.get("max"):
        return ctrl["max"]
    if any(w in head for w in MIN_WORDS) and ctrl.get("min"):
        return ctrl["min"]

    m = re.search(r"(?:to|=|of|at)\s*[\"'`]?(-?\d+(?:\.\d+)?)", low[:90])
    if not m:
        m = re.search(r"^[^.]{0,40}?(-?\d+(?:\.\d+)?)", low)
    if not m:
        return None

    val = m.group(1)
    # Refuse a value the control cannot take; the sentence was about something
    # else and matching it would produce a button that lies.
    try:
        v = float(val)
        if ctrl.get("min") not in (None, "") and v < float(ctrl["min"]):
            return None
        if ctrl.get("max") not in (None, "") and v > float(ctrl["max"]):
            return None
    except (TypeError, ValueError):
        pass
    return val


def resolve_option(window, whole, ctrl):
    """The option a select/radio should take."""
    best = None
    for opt in ctrl.get("options", []):
        for cand in (opt.get("label") or "", opt.get("value") or ""):
            cand = cand.strip()
            if len(cand) < 3 or normalise(cand) in STOPWORDS:
                continue
            # A distinctive option name may appear anywhere in the step; a
            # short one has to be next to the control's own label.
            hay = whole if len(cand) >= 5 else window[:80]
            if re.search(r"(?<![a-z0-9])" + re.escape(cand) + r"(?![a-z0-9])", hay, re.I):
                if best is None or len(cand) > len(best[1]):
                    best = (opt.get("value") or opt.get("label"), cand)
    return best[0] if best else None


BOOL_ON = re.compile(r"\b(enable|turn on|switch on|check|tick|activate|with)\b", re.I)
BOOL_OFF = re.compile(r"\b(disable|turn off|switch off|uncheck|untick|deactivate|without)\b", re.I)


def parse_step(step_html, ctrls):
    """A preset for one experiment step, or None if nothing resolved."""
    text = text_of(step_html)
    if not text:
        return None

    sets = []
    used = set()

    for ctrl in ctrls:
        if ctrl["kind"] == "button" or not ctrl.get("label"):
            continue
        pat = label_pattern(ctrl["label"])
        if not pat:
            continue
        m = pat.search(text)
        if not m:
            continue
        window = text[m.end():m.end() + 120]

        value = None
        if ctrl["kind"] in ("range", "number"):
            value = resolve_number(window, ctrl)
        elif ctrl["kind"] in ("select", "radio"):
            value = resolve_option(window, text, ctrl)
        elif ctrl["kind"] == "checkbox":
            near = text[max(0, m.start() - 40):m.end() + 60]
            if BOOL_OFF.search(near):
                value = False
            elif BOOL_ON.search(near):
                value = True

        if value is None:
            continue
        if ctrl["id"] in used:
            continue
        used.add(ctrl["id"])
        sets.append({"id": ctrl["id"], "kind": ctrl["kind"], "value": value})

    # An option named without its control's label ("Select the RANK() function").
    for ctrl in ctrls:
        if ctrl["kind"] not in ("select", "radio") or ctrl["id"] in used:
            continue
        value = resolve_option("", text, ctrl)
        if value is None:
            continue
        used.add(ctrl["id"])
        sets.append({"id": ctrl["id"], "kind": ctrl["kind"], "value": value})

    clicks = []
    for ctrl in ctrls:
        if ctrl["kind"] != "button" or not ctrl.get("label"):
            continue
        lbl = ctrl["label"].strip()
        if len(lbl) < 3:
            continue
        if re.search(r"\b(click|press|hit|tap|then)\b[^.]{0,40}" + re.escape(lbl), text, re.I):
            clicks.append(ctrl["id"])

    if not sets and not clicks:
        return None
    return {"set": sets, "click": clicks}


MAX_ACTIONS = 8


def key_targets(ctrls, src=""):
    """The one or two sliders the arrow keys should drive.

    Every visualisation on the site is driven by a pointer, and a slider is
    already keyboard-accessible once focused - but the drag surfaces are not,
    and nothing tells a keyboard user which control matters. This picks the
    page's widest-range slider as the primary axis and the next widest as the
    secondary, which is the same heuristic derive_preset uses and is right far
    more often than it is wrong.

    Returns {} when the page has no bounded slider at all, and the runtime
    then leaves the page exactly as it found it.
    """
    ranked = []
    for c in ctrls:
        if c["kind"] != "range":
            continue
        lo_s = c["min"] if c["min"] != "" else "0"
        hi_s = c["max"] if c["max"] != "" else "100"
        try:
            lo, hi = float(lo_s), float(hi_s)
            step = float(c["step"] or 1)
        except ValueError:
            continue
        if hi <= lo or step <= 0:
            continue
        ranked.append(((hi - lo) / step, {
            "id": c["id"], "label": c.get("label") or _fallback_label(c),
            "min": lo, "max": hi, "step": step,
        }))

    ranked.sort(key=lambda r: -r[0])
    out = {}
    if ranked:
        out["primary"] = ranked[0][1]
    if len(ranked) > 1:
        out["secondary"] = ranked[1][1]

    # Half the site has no slider at all - the SQL labs, most of the CNN
    # pages - and a select is just as drivable with an arrow key. Fill any
    # empty slot with the longest option list rather than leaving the
    # visualisation a focus stop that does nothing.
    selects = sorted(
        [c for c in ctrls
         if c["kind"] == "select" and len(c.get("options") or []) > 1],
        key=lambda c: -len(c["options"]))
    for c in selects:
        entry = {"id": c["id"], "label": c.get("label") or _fallback_label(c),
                 "kind": "select", "count": len(c["options"])}
        if "primary" not in out:
            out["primary"] = entry
        elif "secondary" not in out and entry["id"] != out["primary"]["id"]:
            out["secondary"] = entry
        else:
            break

    # A bounded number field is a slider with a different skin - same min/max
    # /step, same meaning for an arrow key - and a checkbox is a two-value
    # axis. Neither was ever offered, which is most of why a quarter of the
    # site had no keyboard route in.
    for c in ctrls:
        if "primary" in out and "secondary" in out:
            break
        if c["kind"] == "number":
            lo, hi = c.get("min", ""), c.get("max", "")
            if lo == "" or hi == "":
                continue
            try:
                lo, hi, step = float(lo), float(hi), float(c["step"] or 1)
            except ValueError:
                continue
            if hi <= lo or step <= 0:
                continue
            entry = {"id": c["id"], "label": c.get("label") or _fallback_label(c),
                     "kind": "number", "min": lo, "max": hi, "step": step}
        elif c["kind"] == "checkbox":
            entry = {"id": c["id"], "label": c.get("label") or _fallback_label(c),
                     "kind": "checkbox"}
        else:
            continue
        if "primary" not in out:
            out["primary"] = entry
        elif entry["id"] != out["primary"]["id"]:
            out["secondary"] = entry

    # Nineteen pages are driven purely by buttons - step through a traversal,
    # pick a split, run an epoch - and have no axis to nudge at all. Those get
    # a selectable action list instead, which is the only honest keyboard
    # equivalent of "click the thing".
    if src:
        acts = action_buttons(src)[:MAX_ACTIONS]
        if acts:
            out["actions"] = acts

    return out


def _fallback_label(ctrl):
    """A name for a control whose markup never gave it one.

    Two pages carry an unlabelled slider and lost their keyboard route over
    it. The id is always there and is always descriptive on this site
    ("thresholdSlider", "k-slider"), so it is a better answer than silence.
    """
    s = re.sub(r"[-_]+", " ", ctrl.get("id") or "").strip()
    s = re.sub(r"(?<=[a-z])(?=[A-Z])", " ", s)
    s = re.sub(r"\b(slider|input|range|select|checkbox|ctrl|control)\b", "", s, flags=re.I)
    s = WS_RE.sub(" ", s).strip()
    return s.capitalize() if s else "Value"


WS_RE = re.compile(r"\s+")


def derive_preset(ctrls):
    """A real experiment built from the controls themselves.

    Roughly two thirds of the pages describe their experiments in prose too
    loose to resolve ("slide sigma wider", "load the Parallel preset"). Rather
    than leave those pages without a prediction, push the widest slider to the
    end of its range - which is a genuine experiment, is guaranteed to be a
    legal value, and needs nothing from the article.
    """
    def one(ctrl, value, title):
        return ({"set": [{"id": ctrl["id"], "kind": ctrl["kind"], "value": value}],
                 "click": []}, title)

    # --- a bounded slider, pushed to the far end ------------------------
    best = None
    for c in ctrls:
        if c["kind"] not in ("range", "number") or not c.get("label"):
            continue
        # HTML's own defaults for a range with no bounds declared.
        lo_s = c["min"] if c["min"] != "" else ("0" if c["kind"] == "range" else "")
        hi_s = c["max"] if c["max"] != "" else ("100" if c["kind"] == "range" else "")
        try:
            lo, hi, cur = float(lo_s), float(hi_s), float(c["value"] or lo_s)
        except (TypeError, ValueError):
            continue
        if hi <= lo:
            continue
        span = hi - lo
        if best is None or span > best[0]:
            best = (span, c, lo, hi, cur, lo_s, hi_s)

    if best:
        _, c, lo, hi, cur, lo_s, hi_s = best
        # Move to whichever end is further away, so something visibly changes.
        to_max = (cur - lo) <= (hi - cur)
        return one(c, hi_s if to_max else lo_s,
                   "set %s to its %s (%s)" % (c["label"], "maximum" if to_max else "minimum",
                                              hi_s if to_max else lo_s))

    # --- an unbounded number box, moved by a meaningful amount ----------
    for c in ctrls:
        if c["kind"] != "number" or not c.get("label"):
            continue
        try:
            cur = float(c["value"])
        except (TypeError, ValueError):
            continue
        target = cur * 2 if cur else 10
        value = str(int(target)) if float(target).is_integer() else str(target)
        return one(c, value, "%s %s to %s" % ("double" if cur else "set",
                                              c["label"], value))

    # --- a selector, switched away from its default --------------------
    for c in ctrls:
        if c["kind"] in ("select", "radio") and len(c.get("options") or []) > 1:
            opt = c["options"][-1]
            if not (opt.get("value") or opt.get("label")):
                continue
            return one(c, opt.get("value") or opt.get("label"),
                       "switch %s to %s" % (c["label"] or "the selector",
                                            opt.get("label") or opt.get("value")))

    # --- failing all that, run the page's own action button ------------
    ACTION = re.compile(
        r"(run|animate|play|start|recognize|calculat|generate|sort|search|"
        r"next|step|train|build|solve|encode|process|go)", re.I)
    RESET = re.compile(r"(reset|clear|undo|back|stop|pause)", re.I)

    for pattern in (ACTION, None):
        for c in ctrls:
            if c["kind"] != "button" or not c.get("label"):
                continue
            if RESET.search(c["label"]):
                continue
            if pattern is None or pattern.search(c["label"]):
                return ({"set": [], "click": [c["id"]]},
                        "press %s" % c["label"])
    return None


def step_title(step_html):
    m = re.search(r"<strong\b[^>]*>(.*?)</strong>", step_html, re.S | re.I)
    label = text_of(m.group(1)) if m else text_of(step_html)
    label = label.rstrip(":. ").strip()
    if len(label) > 80:
        label = label[:77].rstrip() + "..."
    return label or "this experiment"


