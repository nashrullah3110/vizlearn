TAKEAWAY_HEAD = re.compile(
    r"<(h[2-6])\b[^>]*>\s*(?:<[^>]+>\s*)*[^<]*?(key takeaway|takeaway|in one line|"
    r"key point|remember|summary)[^<]*</\1>", re.I)

