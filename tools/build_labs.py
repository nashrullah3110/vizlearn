def run_button(index, title):
    return ('<button class="vz-run" type="button" data-vz-run="%d" '
            'aria-label="Run this experiment in the visualisation: %s">%s'
            '<span>Run this</span></button>'
            % (index, html.escape(title, quote=True), svg("play")))


def predict_markup(preset_index, title):
    return (
        '<section class="vz-predict" data-vz-preset="%d" aria-labelledby="vz-predict-h">'
        '<div class="vz-section-head">%s<h2 id="vz-predict-h">Predict, then reveal</h2>'
        '<span class="vz-rule"></span></div>'
        '<p class="vz-predict-q">About to run: <strong>%s</strong>. '
        'Before it does &mdash; what happens to '
        '<strong class="vz-predict-readout">the readout</strong>?</p>'
        '<div class="vz-predict-opts">'
        '<button type="button" class="vz-predict-opt" data-vz-guess="up">It goes up</button>'
        '<button type="button" class="vz-predict-opt" data-vz-guess="down">It goes down</button>'
        '<button type="button" class="vz-predict-opt" data-vz-guess="same">It stays the same</button>'
        "</div>"
        '<div class="vz-predict-result" hidden></div>'
        '<p class="vz-predict-hint">Committing to an answer first is the point &mdash; '
        'the reveal runs the experiment on the visualisation above and reads the real '
        'value back, so nothing here is scripted.</p>'
        "</section>"
        % (preset_index, svg("target"), html.escape(title))
    )


def check_markup(questions, cards):
    body = []

    for q in questions:
        opts = "".join(
            '<button type="button" class="vz-q-opt" data-vz-correct="%d">%s</button>'
            % (1 if i == q["answer"] else 0, html.escape(opt))
            for i, opt in enumerate(q["options"])
        )
        why = ('<p class="vz-q-why" hidden>%s</p>' % q["why"]) if q.get("why") else ""
        body.append(
            '<li class="vz-q"><p class="vz-q-text">%s</p>'
            '<div class="vz-q-opts">%s</div>%s</li>'
            % (html.escape(q["q"]), opts, why)
        )

    for prompt, answer in cards:
        body.append(
            '<li class="vz-q vz-q-card"><p class="vz-q-text">%s</p>'
            '<button type="button" class="vz-q-reveal" data-vz-reveal>Show answer</button>'
            '<p class="vz-q-answer" hidden>%s</p></li>'
            % (html.escape(prompt), html.escape(answer))
        )

    kind = "Check yourself" if questions else "Recall check"
    intro = ("Answer without scrolling back up." if questions else
             "Say the answer out loud before you reveal it &mdash; recalling it is "
             "what makes it stick, and rereading it is not.")

    return (
        '<section class="vz-check" aria-labelledby="vz-check-h">'
        '<div class="vz-section-head">%s<h2 id="vz-check-h">%s</h2>'
        '<span class="vz-rule"></span>'
        '<span class="vz-check-score" aria-live="polite">0 of %d</span></div>'
        '<p class="vz-check-intro">%s</p>'
        '<ol class="vz-check-list">%s</ol>'
        "</section>"
        % (svg("check"), kind, len(body), intro, "".join(body))
    )


