def viz_container_id(src):
    """The id of the main visualisation element, for scroll-into-view."""
    for pat in (r'<svg\b[^>]*\bid="([^"]+)"', r'<canvas\b[^>]*\bid="([^"]+)"'):
        m = re.search(pat, src, re.I)
        if m:
            return m.group(1)
    return ""


def process(path, rel, authored):
    src = open(path, encoding="utf-8").read()
    src = BLOCK.sub("", src)
    src = RUN_BTN.sub("", src)

    ctrls = controls(src)

    # --- experiments --------------------------------------------------
    presets = []
    inserts = []          # (position, markup) applied right-to-left
    m = EXP_HEADING.search(src)
    if m:
        for open_end, close_start in top_level_items(src, m.end()):
            inner = src[open_end:close_start]
            preset = parse_step(inner, ctrls)
            if not preset:
                continue
            title = step_title(inner)
            presets.append(preset)
            inserts.append((close_start, run_button(len(presets) - 1, title)))
            preset["title"] = title

    for pos, markup in sorted(inserts, reverse=True):
        src = src[:pos] + markup + src[pos:]

    # --- lab block ----------------------------------------------------
    reads = readouts(src, ctrls)
    pieces = []

    # Prefer an experiment that moves a slider: a continuous control gives the
    # readout something to respond to, where a button may just reset the page.
    best = None
    for i, p in enumerate(presets):
        if any(s["kind"] in ("range", "number") for s in p["set"]):
            best = i
            break
    if best is None and presets:
        best = 0

    if best is None:
        # Nothing in the prose resolved; build one from the controls instead.
        derived = derive_preset(ctrls)
        if derived:
            preset, title = derived
            preset["title"] = title
            presets.append(preset)
            best = len(presets) - 1

    if best is not None and reads:
        pieces.append(predict_markup(best, presets[best]["title"]))

    questions = authored.get("check") or []
    cards = [] if questions else flashcards(src)
    if questions or cards:
        pieces.append(check_markup(questions, cards))

    config = {
        "presets": [{"set": p["set"], "click": p["click"]} for p in presets],
        "readouts": reads,
        "viz": viz_container_id(src),
        "keys": key_targets(ctrls, src),
    }

    block = (
        BEGIN + "\n"
        '<div class="vz-lab">%s</div>\n'
        '<script type="application/json" id="vz-lab-data">%s</script>\n'
        % ("".join(pieces), json.dumps(config, ensure_ascii=False))
        + END + "\n"
    )

    # Above the module furniture, and above the footer marker rather than the
    # <footer> element - the footer is generated between markers, so anchoring
    # inside that region would get this block deleted on the next footer run.
    for marker in ("<!-- VIZLEARN:MODULE:BEGIN", "<!-- VIZLEARN:FOOTER:BEGIN", "<footer"):
        anchor = src.rfind(marker)
        if anchor != -1:
            break
    if anchor == -1:
        anchor = src.rindex("</body>")
    anchor = src.rfind("\n", 0, anchor) + 1
    src = src[:anchor] + block + src[anchor:]

    open(path, "w", encoding="utf-8").write(src)
    return {
        "runnable": len(inserts),
        "predict": 1 if (best is not None and reads) else 0,
        "mcq": 1 if questions else 0,
        "cards": 1 if cards else 0,
        "nocheck": 0 if (questions or cards) else 1,
        "rel": rel,
        # Handed back for the practice bank, so the questions on /practice/ and
        # the ones on the module are the same objects rather than a second
        # transcription that could drift.
        "questions": questions,
        "cards_list": cards,
    }


BANK_OUT = os.path.join(ROOT, "assets", "practice-bank.js")

BANK_HEADER = """/* GENERATED FILE - do not edit by hand.
 * Source: the same checks tools/build_labs.py writes into each module.
 * Rebuild: python3 tools/build_labs.py
 */
"""


def write_bank(entries):
    """The question bank /practice/ draws from.

    One record per module that has a check, holding either its authored
    multiple-choice questions or the recall cards derived from its own prose.
    Nothing is invented here that the module page does not already show.
    """
    entries.sort(key=lambda e: (e["cat"], e["title"]))
    with open(BANK_OUT, "w", encoding="utf-8") as fh:
        fh.write(BANK_HEADER)
        fh.write("window.VIZLEARN_PRACTICE = %s;\n"
                 % json.dumps(entries, ensure_ascii=False, indent=1))
    total = sum(len(e["q"]) for e in entries)
    print("practice bank             : %d questions across %d modules"
          % (total, len(entries)))


def main():
    mods = {m["path"] for m in modules()}
    meta = {m["path"]: m for m in modules()}
    bank = []
    files = sorted(glob.glob(os.path.join(ROOT, "*", "*.html")))
    files = [f for f in files
             if os.path.basename(os.path.dirname(f)) not in ("tools", "assets", "node_modules")]

    runnable = pages_runnable = predict = mcq = cards = 0
    no_check = []
    no_predict = []
    pages = 0

    for f in files:
        rel = os.path.relpath(f, ROOT)
        if rel not in mods:
            continue
        pages += 1
        r = process(f, rel, LABS.get(rel, {}))
        runnable += r["runnable"]
        pages_runnable += 1 if r["runnable"] else 0
        predict += r["predict"]
        mcq += r["mcq"]
        cards += r["cards"]
        if r["nocheck"]:
            no_check.append(rel)
        if not r["predict"]:
            no_predict.append(rel)

        qs = [{"t": q["q"], "o": q["options"], "a": q["answer"], "w": q.get("why", "")}
              for q in r["questions"]]
        qs += [{"t": prompt, "ans": answer} for prompt, answer in r["cards_list"]]
        if qs:
            m = meta[rel]
            bank.append({"path": rel, "title": m["title"],
                         "cat": m["category"], "q": qs})

    write_bank(bank)
    print("pages processed           : %d" % pages)
    print("runnable experiments      : %d across %d pages" % (runnable, pages_runnable))
    print("predict-then-reveal       : %d pages" % predict)
    print("checks - authored MCQ     : %d pages" % mcq)
    print("checks - recall cards     : %d pages" % cards)
    if no_check:
        print("\nNO CHECK on %d page(s):" % len(no_check))
        for r in no_check[:20]:
            print("  -", r)
    if no_predict:
        print("\nNO PREDICTION on %d page(s):" % len(no_predict))
        for r in no_predict[:20]:
            print("  -", r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
